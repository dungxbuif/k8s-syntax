function optionNames(flag) {
  return flag.split(',').map((name) => name.trim().split('=')[0]).filter((name) => name.startsWith('-'));
}

function slug(value) {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

function makeOptionQuestion(command, option, index) {
  const names = optionNames(option.flag);
  const longName = names.find((name) => name.startsWith('--')) || names[0];
  const commandTokens = command === 'global' ? ['kubectl'] : ['kubectl', ...command.split(' ')];
  const displayCommand = command === 'global' ? 'kubectl <command>' : 'kubectl ' + command;
  return {
    id: 'option-' + slug(command) + '-' + slug(longName) + '-' + index,
    mode: 'command',
    category: 'option-catalog',
    difficulty: 2,
    prompt: 'Gõ cú pháp ' + displayCommand + ' có dùng option ' + longName + '.',
    expected: { mustInclude: commandTokens, anyOf: [names] },
    explanation: option.description + ' Đây là bài syntax tối thiểu để nhớ đúng tên option và alias của nó.',
    source: DOCS.quick,
    tags: ['option-catalog', command],
  };
}

const optionDrillQuestions = [
  ...GLOBAL_OPTIONS.map((option, index) => makeOptionQuestion('global', option, index)),
  ...Object.entries(COMMAND_OPTIONS).flatMap(([command, options]) => options.map((option, index) => makeOptionQuestion(command, option, index))),
];

export const questions = [...baseQuestions, ...optionDrillQuestions];

